// Generates src/data/audio.ts from assets/audio/letters/manifest.json.
// Metro needs literal require() paths, so the map cannot be built at runtime.
// Run: npm run gen:audio
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const manifest = JSON.parse(
  readFileSync(fileURLToPath(new URL('assets/audio/letters/manifest.json', root)), 'utf8'),
);

const lines = manifest
  .map((m) => m.file)
  .sort()
  .map((f) => `  'letters/${f}': require('../../assets/audio/letters/${f}'),`);

const out = `// GENERATED by scripts/gen-audio-map.mjs from assets/audio/letters/manifest.json.
// Do not edit by hand; run \`npm run gen:audio\`.

/** Maps an entry's \`audio\` path to the bundled asset id. */
export const AUDIO: Record<string, number> = {
${lines.join('\n')}
};
`;

writeFileSync(fileURLToPath(new URL('src/data/audio.ts', root)), out);
console.log(`wrote src/data/audio.ts with ${lines.length} clips`);
