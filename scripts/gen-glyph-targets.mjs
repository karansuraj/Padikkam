// Generates src/data/glyph-targets.ts: for each letter in src/data/letters.ts, the glyph outline
// (SVG path, 0..100 box) and its skeleton (centreline polylines, unit square) from Noto Sans Malayalam.
// Run: npm run gen:glyphs
// Optional: npm run gen:glyphs -- --preview /path/to/preview.svg   (outline + skeleton overlay for review)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import {
  fillPolygons,
  fitPolygons,
  flattenCommands,
  pathData,
  simplify,
  skeletonPolylines,
  thin,
} from './glyph-lib.mjs';

const root = new URL('../', import.meta.url);
const at = (rel) => fileURLToPath(new URL(rel, root));

const SIZE = 256; // raster resolution for thinning
const MARGIN = 0.08; // empty border around each glyph in the unit square
const SPUR = 12; // pixels; thinning whiskers shorter than this are dropped

// The font turns these sequences into one glyph with substitution rules that opentype.js does not run.
const LIGATURES = { 'റ്റ': ['rrarramlym'] };

const font = (() => {
  const buf = readFileSync(at('scripts/glyph/NotoSansMalayalam-Regular.ttf'));
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
})();

const glyphsFor = (ml) => {
  const names = LIGATURES[ml];
  if (!names) return [...ml].map((ch) => font.charToGlyph(ch));
  const wanted = new Set(names);
  const found = [];
  for (let i = 0; i < font.glyphs.length; i++) {
    const g = font.glyphs.get(i);
    if (wanted.has(g.name)) found.push(g);
  }
  if (found.length !== names.length) throw new Error(`glyph not found for ${ml}: ${names}`);
  return names.map((n) => found.find((g) => g.name === n));
};

/** Outline polygons for a letter, laid out left to right in font units (y up). */
function outline(ml) {
  let cursor = 0;
  const polygons = [];
  for (const glyph of glyphsFor(ml)) {
    if (glyph.index === 0) throw new Error(`no glyph for ${ml}`);
    for (const poly of flattenCommands(glyph.path.commands)) {
      polygons.push(poly.map(([x, y]) => [x + cursor, y]));
    }
    cursor += glyph.advanceWidth;
  }
  return polygons;
}

const round3 = (n) => Math.round(n * 1000) / 1000;

const { LETTERS } = await import('../src/data/letters.ts');
const targets = {};
for (const letter of LETTERS) {
  const { polygons } = fitPolygons(outline(letter.ml), MARGIN);
  const strokes = skeletonPolylines(thin(fillPolygons(polygons, SIZE), SIZE), SIZE, SPUR);
  if (strokes.length === 0) throw new Error(`empty skeleton for ${letter.ml}`);
  targets[letter.id] = {
    d: pathData(polygons.map((p) => simplify([...p, p[0]], 0.0015).slice(0, -1))),
    strokes: strokes.map((s) => s.map(([x, y]) => [round3(x), round3(y)])),
  };
}

const lines = Object.entries(targets).map(([id, t]) => `  ${JSON.stringify(id)}: ${JSON.stringify(t)},`);
writeFileSync(
  at('src/data/glyph-targets.ts'),
  `// Generated by scripts/gen-glyph-targets.mjs (npm run gen:glyphs). Do not edit by hand.
// Outlines and skeletons derived from Noto Sans Malayalam v2.104, SIL Open Font License 1.1,
// Copyright 2022 The Noto Project Authors (https://github.com/notofonts/malayalam).
// \`d\` is an SVG path on a 0..100 box; \`strokes\` are skeleton polylines in the unit square.
export const GLYPH_TARGETS: Record<string, { d: string; strokes: [number, number][][] }> = {
${lines.join('\n')}
};
`,
);
console.log(`wrote src/data/glyph-targets.ts: ${LETTERS.length} letters`);

const previewAt = process.argv.indexOf('--preview');
if (previewAt > 0) {
  const cell = 120;
  const cols = 8;
  const ids = Object.keys(targets);
  const rows = Math.ceil(ids.length / cols);
  const body = ids
    .map((id, i) => {
      const t = targets[id];
      const ox = (i % cols) * cell;
      const oy = Math.floor(i / cols) * cell;
      const roman = LETTERS.find((l) => l.id === id).roman;
      const skel = t.strokes
        .map((s) => `<polyline fill="none" stroke="#d00" stroke-width="1.2" points="${s.map(([x, y]) => `${(x * 100).toFixed(1)},${(y * 100).toFixed(1)}`).join(' ')}"/>`)
        .join('');
      return `<g transform="translate(${ox + 10} ${oy + 10})"><rect width="100" height="100" fill="none" stroke="#ccc"/><path d="${t.d}" fill="#bbb" fill-rule="nonzero"/>${skel}<text x="2" y="110" font-size="8">${roman}</text></g>`;
    })
    .join('');
  writeFileSync(process.argv[previewAt + 1], `<svg xmlns="http://www.w3.org/2000/svg" width="${cols * cell + 20}" height="${rows * cell + 20}" viewBox="0 0 ${cols * cell + 20} ${rows * cell + 20}"><rect width="100%" height="100%" fill="#fff"/>${body}</svg>`);
  console.log(`wrote preview ${process.argv[previewAt + 1]}`);
}
