// Pure part of the audio map generator: manifests in, file contents out.
// Metro needs literal require() paths, so the map cannot be built at runtime.

const https = (url) => (url ?? '').replace(/^http:\/\//, 'https://');

/**
 * @param {{ letters: object[], words: object[], vocab: { id: string, ml: string }[] }} input
 * @returns {{ audioTs: string, credits: object[] }}
 */
export function buildAudioFiles({ letters, words, vocab }) {
  const entries = [
    ...letters.map((m) => ({ key: `letters/${m.file}`, dir: 'letters', file: m.file })),
    ...words.map((m) => ({ key: `words/${m.file}`, dir: 'words', file: m.file })),
  ].sort((a, b) => (a.key < b.key ? -1 : 1));

  const lines = entries.map((e) => `  '${e.key}': require('../../assets/audio/${e.dir}/${e.file}'),`);
  const audioTs = `// GENERATED by scripts/gen-audio-map.mjs from the audio manifests in assets/audio.
// Do not edit by hand; run \`npm run gen:audio\`.

/** Maps an entry's \`audio\` path to the bundled asset id. */
export const AUDIO: Record<string, number> = {
${lines.join('\n')}
};
`;

  const wordLabel = new Map(vocab.map((v) => [v.id, v.ml]));
  const credit = (label, m) => ({
    label,
    speaker: m.speaker ?? '',
    license: m.license,
    licenseUrl: https(m.licenseUrl),
    sourcePage: m.sourcePage,
  });
  const credits = [
    ...letters.map((m) => credit(m.letter, m)),
    ...words.map((m) => credit(wordLabel.get(m.id) ?? m.id, m)),
  ];
  return { audioTs, credits };
}
