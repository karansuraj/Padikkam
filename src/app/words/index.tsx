import { router } from 'expo-router';
import { ScrollView, View } from 'react-native';
import { FadeIn } from '../../components/FadeIn';
import { PressableScale } from '../../components/PressableScale';
import { makeStyles } from '../../theme';
import { AUDIO } from '../../data/audio';
import { TOPICS, VOCAB_BY_ID } from '../../data/vocab';
import { Text } from '../../components/Text';

export default function Words() {
  const styles = useStyles();
  return (
    <FadeIn style={styles.fill}>
      <ScrollView contentContainerStyle={styles.container}>
        <Text style={styles.intro}>
          Starter words from open data, grouped by topic. Romanization is generated by rule, so treat it as a guide.
        </Text>
        {TOPICS.map((t) => {
          const withAudio = t.entryIds.filter((id) => {
            const audio = VOCAB_BY_ID.get(id)?.audio;
            return !!audio && AUDIO[audio] !== undefined;
          }).length;
          return (
            <PressableScale key={t.id} style={styles.row} deferPress onPress={() => router.push(`/words/${t.id}`)}>
              <View style={styles.rowText}>
                <Text style={styles.title}>{t.title}</Text>
                <Text style={styles.sub}>{`${t.entryIds.length} words${withAudio > 0 ? `, ${withAudio} with audio` : ''}`}</Text>
              </View>
            </PressableScale>
          );
        })}
      </ScrollView>
    </FadeIn>
  );
}

const useStyles = makeStyles((c) => ({
  fill: { flex: 1 },
  container: { padding: 20, gap: 10, paddingBottom: 40 },
  intro: { fontSize: 14, color: c.textMuted, marginBottom: 6 },
  row: { borderRadius: 12, borderWidth: 1, borderColor: c.border, backgroundColor: c.tint, padding: 16 },
  rowText: { gap: 4 },
  title: { fontSize: 17, fontWeight: '600', color: c.text },
  sub: { fontSize: 13, color: c.textMuted },
}));
